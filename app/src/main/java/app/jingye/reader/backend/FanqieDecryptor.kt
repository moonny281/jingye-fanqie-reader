    fun isPua(ch: Char): Boolean = ch.code in PUA_START..PUA_END

    fun hasObfuscation(text: String): Boolean = text.any { isPua(it) }

    fun decryptText(text: String): String {
        if (text.isEmpty() || !hasObfuscation(text)) return text
        val sb = StringBuilder(text.length)
        for (ch in text) {
            sb.append(FONT_MAP[ch.code] ?: ch)
        }
        return sb.toString()
    }

    fun remainingPua(text: String): List<Char> {
        val seen = ArrayList<Char>()
        for (ch in text) {
            if (isPua(ch) && ch !in seen) seen.add(ch)
        }
        return seen
    }
